"""
Report Generation Specialist Agent

Consolidates outputs from Trend, Clustering, and Root-Cause agents
into a polished executive briefing document.
"""

import sys
from pathlib import Path

# Resolve project root and ensure it is on sys.path
_PROJECT_ROOT = Path(__file__).resolve().parents[2]
if str(_PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(_PROJECT_ROOT))

from typing import Dict, Any, Optional

from config.settings import REPORTS_DIR
from src.utils.logger import get_logger
from src.utils.helpers import ensure_dir

logger = get_logger(__name__)


def run_report_agent(
    user_query: str,
    trend_insights: Optional[Dict[str, Any]] = None,
    cluster_insights: Optional[Dict[str, Any]] = None,
    root_cause_report: Optional[Dict[str, Any]] = None,
) -> str:
    """Generate a unified executive briefing markdown report from all specialist outputs."""
    logger.info("Report Agent generating briefing for query: '%s'", user_query)

    issue = trend_insights.get("target_issue", "Cross-category") if trend_insights else "General"
    company = trend_insights.get("target_company", "All Institutions") if trend_insights else "All Institutions"

    lines = [
        f"# Executive Investigation Briefing: {issue}",
        f"**Target Institution:** {company}  ",
        f"**Original Query:** *\"{user_query}\"*  ",
        "**Generated by:** Multi-Agent Compliance Coordination System (LangGraph)  ",
        "",
        "---",
        "",
        "## 1. Executive Summary",
        f"A multi-agent autonomous investigation was executed focusing on customer complaints regarding **{issue}** at **{company}**.",
    ]

    # Trend Section
    if trend_insights and trend_insights.get("status") == "success":
        lines.extend([
            "",
            "## 2. Trend & Volume Analytics",
            f"- **Total Matched Complaints:** {trend_insights.get('total_matched_volume', 0):,}",
            f"- **Average Monthly Volume:** {trend_insights.get('average_monthly_volume', 0):.0f} complaints/mo",
            f"- **Peak Monthly Volume:** {trend_insights.get('peak_monthly_volume', 0):,} complaints",
            f"- **Trajectory:** `{trend_insights.get('velocity_direction', 'Stable')}`",
        ])
        spikes = trend_insights.get("detected_spikes", [])
        if spikes:
            lines.append("- **Detected Volume Surges:**")
            for spk in spikes:
                lines.append(f"  - {spk}")

    # Cluster Section
    if cluster_insights and cluster_insights.get("status") == "success":
        lines.extend([
            "",
            "## 3. Discovered Semantic Themes & Topic Clusters",
            f"- **Salient Complaint Keywords:** `{', '.join(cluster_insights.get('salient_keywords', []))}`",
        ])
        for theme in cluster_insights.get("dominant_themes", [])[:2]:
            lines.append(
                f"- **Cluster {theme['cluster_id']}** ({theme['complaint_count']:,} complaints, {theme['share_pct']}%): "
                f"Themes around *{theme['theme_keywords']}*"
            )

    # Root Cause Section
    if root_cause_report and root_cause_report.get("status") == "success":
        lines.extend([
            "",
            "## 4. Root-Cause Hypothesis & Operational Recommendations",
            "> [!WARNING] **Methodological Notice**: Hypotheses below are operational explanations derived from complaint patterns and have not been validated by internal system audits.",
            "",
            f"**Possible Operational Root Cause:**",
            f"> {root_cause_report.get('possible_root_cause')}",
            "",
            "**Recommended Engineering & Operations Actions:**",
            root_cause_report.get("recommended_investigation", "No recommendations recorded."),
            "",
            "### Supporting Verbatim Complaint Citations",
        ])
        for cit in root_cause_report.get("representative_citations", []):
            lines.append(
                f"- **[{cit['complaint_id']}]** ({cit['channel']}, {cit['sentiment']}, {cit['resolution_status']}): "
                f"\"{cit['narrative'][:140]}...\""
            )

    lines.extend([
        "",
        "---",
        "*Briefing compiled autonomously via LangGraph StateGraph coordinator.*",
    ])

    briefing_text = "\n".join(lines)

    # Persist briefing
    briefing_dir = REPORTS_DIR / "agent_briefings"
    ensure_dir(briefing_dir)
    safe_name = "".join([c if c.isalnum() else "_" for c in issue])[:30]
    out_file = briefing_dir / f"briefing_{safe_name}.md"

    with open(out_file, "w", encoding="utf-8") as f:
        f.write(briefing_text)
    logger.info("Saved agent briefing to: %s", out_file)

    return briefing_text
